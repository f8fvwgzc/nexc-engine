"""Regenerates `nexc_runtime/rpc/runtime_pb2.py`, its `.pyi` and `runtime_grpc.py` from the
vendored `backend/proto/nexc/runtime/v1/runtime.proto` (the single source of the wire).

    uv run python scripts/gen_proto.py        # or `make proto-runtime` at the repo root

Needs the `grpcio-tools` dev dependency (it carries protoc and the well-known types); the
grpclib plugin comes with `grpclib`. The generated files are committed, so a build machine
needs neither.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUNTIME = HERE.parent
PROTO = RUNTIME.parent / "backend" / "proto" / "nexc" / "runtime" / "v1" / "runtime.proto"
OUT = RUNTIME / "src" / "nexc_runtime" / "rpc"
HEADER = "# Generated by scripts/gen_proto.py from backend/proto/nexc/runtime/v1/runtime.proto. Do not edit.\n"


def main() -> None:
    import grpc_tools  # noqa: PLC0415 - a dev dependency, imported where it is needed

    well_known = Path(grpc_tools.__file__).parent / "_proto"
    with tempfile.TemporaryDirectory() as tmp:
        # Compiled from a flat directory so the module is `runtime_pb2`, not a deep package.
        src = Path(tmp) / "src"
        src.mkdir()
        shutil.copy(PROTO, src / "runtime.proto")
        gen = Path(tmp) / "gen"
        gen.mkdir()
        plugin = shutil.which("protoc-gen-grpclib_python", path=str(Path(sys.executable).parent))
        if plugin is None:
            sys.exit("protoc-gen-grpclib_python not found: run `uv sync` first")
        subprocess.run(  # noqa: S603 - fixed arguments, no shell
            [
                sys.executable,
                "-m",
                "grpc_tools.protoc",
                f"-I{src}",
                f"-I{well_known}",
                f"--plugin=protoc-gen-grpclib_python={plugin}",
                f"--python_out={gen}",
                f"--pyi_out={gen}",
                f"--grpclib_python_out={gen}",
                "runtime.proto",
            ],
            check=True,
        )
        OUT.mkdir(parents=True, exist_ok=True)
        for name in ("runtime_pb2.py", "runtime_pb2.pyi", "runtime_grpc.py"):
            text = (gen / name).read_text()
            # The plugins import the message module by its bare name; the package is ours.
            text = text.replace("import runtime_pb2\n", "from . import runtime_pb2\n")
            (OUT / name).write_text(HEADER + text)
    print(f"wrote {OUT.relative_to(RUNTIME)}/runtime_pb2.py, runtime_pb2.pyi, runtime_grpc.py")


if __name__ == "__main__":
    main()
