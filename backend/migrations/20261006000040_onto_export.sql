-- "Ask the audit" (AgentSecOps phase 3): the trace is exported to onto-intelli
-- as ontology facts. What is new goes through an outbox the tables fill
-- themselves, so an export never depends on the order in which concurrent
-- writers commit; the first pass over a workspace backfills what was there
-- before the feature was turned on.

-- Insertion order of spans, for the backfill: ids are UUID v7 (the order
-- spans started), but batches of different runs land in the table in any
-- order. Not part of the span's hash.
ALTER TABLE agent_spans
    ADD COLUMN ingested_seq bigint GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX agent_spans_ingested_idx ON agent_spans (ingested_seq);

-- What still has to reach onto-intelli: a span that was written, a run that
-- finished (its status and cost), an agent whose policy changed. Rows are
-- claimed with SKIP LOCKED and deleted once onto-intelli acknowledged them,
-- so a span is exported at least once and instances share the work.
CREATE TABLE onto_export_queue (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id  uuid NOT NULL,
    kind          text NOT NULL CHECK (kind IN ('span', 'run', 'agent')),
    subject_id    uuid NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX onto_export_queue_workspace_idx ON onto_export_queue (workspace_id, id);

CREATE FUNCTION onto_export_enqueue_span() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO onto_export_queue (workspace_id, kind, subject_id)
    SELECT g.workspace_id, 'span', NEW.id
      FROM runs r JOIN graphs g ON g.id = r.graph_id
     WHERE r.id = NEW.run_id AND g.workspace_id IS NOT NULL;
    RETURN NULL;
END $$;
CREATE TRIGGER agent_spans_onto_export
    AFTER INSERT ON agent_spans
    FOR EACH ROW EXECUTE FUNCTION onto_export_enqueue_span();

CREATE FUNCTION onto_export_enqueue_run() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO onto_export_queue (workspace_id, kind, subject_id)
    SELECT g.workspace_id, 'run', NEW.id
      FROM graphs g
     WHERE g.id = NEW.graph_id AND g.workspace_id IS NOT NULL;
    RETURN NULL;
END $$;
CREATE TRIGGER runs_onto_export
    AFTER UPDATE OF finished_at ON runs
    FOR EACH ROW
    WHEN (OLD.finished_at IS NULL AND NEW.finished_at IS NOT NULL)
    EXECUTE FUNCTION onto_export_enqueue_run();

CREATE FUNCTION onto_export_enqueue_agent() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.workspace_id IS NOT NULL THEN
        INSERT INTO onto_export_queue (workspace_id, kind, subject_id)
        VALUES (NEW.workspace_id, 'agent', NEW.id);
    END IF;
    RETURN NULL;
END $$;
CREATE TRIGGER agents_onto_export
    AFTER INSERT OR UPDATE OF name, role, model, status, capabilities, policy_version, workspace_id ON agents
    FOR EACH ROW EXECUTE FUNCTION onto_export_enqueue_agent();

-- Where the export of each workspace stands (one onto-intelli workspace per
-- nexc workspace). A workspace without a row has not been exported yet: the
-- first pass backfills every span, finished run and agent it has, in order,
-- and only then follows the queue.
CREATE TABLE onto_export_cursors (
    workspace_id        uuid PRIMARY KEY REFERENCES workspaces (id) ON DELETE CASCADE,
    -- Backfill position: every span with a lower or equal sequence is exported.
    span_seq            bigint NOT NULL DEFAULT 0 CHECK (span_seq >= 0),
    -- Where the backfill stops: the first span the queue holds, fixed when the
    -- backfill starts, so a span is sent by one of the two, never both.
    backfill_before     bigint,
    -- Set once the backfill of the workspace is complete.
    backfilled_at       timestamptz,
    spans_exported      bigint NOT NULL DEFAULT 0,
    records_exported    bigint NOT NULL DEFAULT 0,
    last_exported_at    timestamptz,
    last_error          text,
    updated_at          timestamptz NOT NULL DEFAULT now()
);
